import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { getAllFarms } from "../src/lib/farms";

const projectRoot = process.cwd();
const projectName = path.basename(projectRoot);
const snapshotDir = path.resolve(projectRoot, "..", `${projectName}-rebuild-content`);

function writeJson(fileName: string, value: unknown) {
  fs.writeFileSync(path.join(snapshotDir, fileName), `${JSON.stringify(value, null, 2)}\n`);
}

function collectRoutes() {
  const routes: string[] = [];
  const appDir = path.join(projectRoot, "src", "app");
  const walk = (directory: string, basePath = "") => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      if (entry.name.startsWith("_") || entry.name === "api") continue;
      const fullPath = path.join(directory, entry.name);
      if (entry.isDirectory()) walk(fullPath, path.join(basePath, entry.name));
      if (entry.isFile() && /^page\.(tsx|js)$/.test(entry.name)) {
        const route = `/${basePath.replace(/\\/g, "/")}`.replace(/\/+/g, "/").replace(/\/$/, "") || "/";
        routes.push(route);
      }
    }
  };
  walk(appDir);
  return Array.from(new Set(routes)).sort();
}

function collectAssets() {
  const assets: Array<{ path: string; bytes: number; sha256: string }> = [];
  const walk = (directory: string, relative = "") => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const fullPath = path.join(directory, entry.name);
      const assetPath = path.join(relative, entry.name).replace(/\\/g, "/");
      if (entry.isDirectory()) walk(fullPath, assetPath);
      else {
        const bytes = fs.readFileSync(fullPath);
        assets.push({ path: assetPath, bytes: bytes.byteLength, sha256: crypto.createHash("sha256").update(bytes).digest("hex") });
      }
    }
  };
  walk(path.join(projectRoot, "public"));
  return assets.sort((a, b) => a.path.localeCompare(b.path));
}

async function main() {
  fs.mkdirSync(snapshotDir, { recursive: true });
  const farms = await getAllFarms();
  const ids = new Set<string>();
  for (const farm of farms) {
    if (ids.has(farm.id)) throw new Error(`Duplicate farm id: ${farm.id}`);
    ids.add(farm.id);
  }
  const routes = collectRoutes();
  const assets = collectAssets();
  const generatedAt = new Date().toISOString();
  writeJson("farms.json", farms);
  writeJson("site-content.json", { farms, generatedAt });
  writeJson("routes.json", { routes, generatedAt });
  writeJson("assets.json", { assets, count: assets.length });
  writeJson("wiki-articles.json", []);
  writeJson("wiki-tools.json", []);
  writeJson("events.json", []);
  writeJson("community.json", {});
  writeJson("staff.json", []);
  writeJson("source-manifest.json", { projectRoot, projectName, generatedAt, farmsCount: farms.length, routesCount: routes.length, assetsCount: assets.length });
  fs.writeFileSync(path.join(snapshotDir, "README.md"), `# ${projectName} rebuild content\n\nGenerated by npm run export:content.\n`);
  console.log(`Snapshot dir: ${snapshotDir}`);
  console.log(`Exported ${farms.length} farms, ${routes.length} routes, and ${assets.length} assets.`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});