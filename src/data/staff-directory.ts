/**
 * Every staff profile gets its own /pfp/<userId>.png path automatically.
 * The <StaffAvatar> component falls back to PUBLIC_STAFF_FALLBACK_AVATAR
 * when the file has not been added to public/pfp/ yet, so there is no
 * separate whitelist to maintain.
 */
export function getPublicStaffAvatarPath(userId: string) {
  return `/pfp/${userId}.png`;
}

